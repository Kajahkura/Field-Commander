"""Create a text-only offline source package; Cargo compiles the embedded dependencies.
No compiled artifacts are included. Original sources, lockfile and vendor checksums
are retained in a deterministic compressed tar archive.
"""
import base64, io, json, lzma, shutil, sys, tarfile, subprocess
from pathlib import Path
source = Path(sys.argv[1]); destination = Path(sys.argv[2])
if destination.exists(): raise SystemExit('Destination must be new')
destination.mkdir(parents=True)
# Cargo still needs manifests/checksums for lockfile resolution of optional and
# other-platform crates, but this WASI build never compiles their source files.
module=Path(__file__).resolve().parents[1]/'_server_islands/operations'
resolved=subprocess.check_output(['cargo','+1.88.0','tree','--offline','--locked','--target','wasm32-wasip1','--edges','normal,build','--prefix','none','--format','{p}','--manifest-path',str(module/'Cargo.toml')],text=True)
compiled={line.split()[0] for line in resolved.splitlines()}
stream=io.BytesIO()
with tarfile.open(fileobj=stream, mode='w') as archive:
    for file in sorted(source.rglob('*')):
        if not file.is_file() or file.relative_to(source).parts[0] in {'src', 'blinkhost.toml'}: continue
        relative=file.relative_to(source)
        if relative.parts[:2]==('vendor','crates'):
            crate=source/'vendor/crates'/relative.parts[2]
            import tomllib
            name=tomllib.loads((crate/'Cargo.toml').read_text())['package']['name']
            if name not in compiled and file.name not in {'Cargo.toml','.cargo-checksum.json','LICENSE','LICENSE-APACHE','LICENSE-MIT','COPYING','COPYRIGHT','README.md'}: continue
        info=tarfile.TarInfo(relative.as_posix()); data=file.read_bytes()
        if file.name=='.cargo-checksum.json' and name not in compiled:
            checks=json.loads(data);checks['files']={path:digest for path,digest in checks['files'].items() if Path(path).name in {'Cargo.toml','LICENSE','LICENSE-APACHE','LICENSE-MIT','COPYING','COPYRIGHT','README.md'}};data=json.dumps(checks).encode()
        info.size=len(data); info.mode=0o644; info.mtime=0
        archive.addfile(info,io.BytesIO(data))
compressed=lzma.compress(stream.getvalue(),preset=9)
(destination/'dependencies.tar.xz.b64').write_bytes(base64.b64encode(compressed))
shutil.copytree(source/'src',destination/'src')
shutil.copyfile(source/'blinkhost.toml',destination/'blinkhost.toml')
(destination/'bootstrap').mkdir()
(destination/'bootstrap/lib.rs').write_text('// Source transport crate. build.rs compiles the application offline.\npub const SOURCE_TRANSPORT_VERSION: u32 = 1;\n')
(destination/'Cargo.toml').write_text('''[package]
name = "field-commander-source-package"
version = "1.0.0"
edition = "2021"
build = "build.rs"
autobins = false

[lib]
path = "bootstrap/lib.rs"
''')
(destination/'Cargo.lock').write_text('''# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "field-commander-source-package"
version = "1.0.0"
''')
(destination/'build.rs').write_text(r'''use std::{env, fs, path::Path, process::Command};
fn decode(input: &[u8]) -> Vec<u8> {
    let mut output=Vec::new(); let mut bits=0u32; let mut count=0;
    for &byte in input {
        if byte==b'=' { break; }
        let value=match byte { b'A'..=b'Z'=>byte-b'A',b'a'..=b'z'=>byte-b'a'+26,b'0'..=b'9'=>byte-b'0'+52,b'+'=>62,b'/'=>63,_=>panic!("Invalid dependency archive encoding") };
        bits=(bits<<6)|value as u32; count+=6;
        if count>=8 { count-=8; output.push((bits>>count) as u8); }
    }
    output
}
''' + (Path(__file__).parent/'compact-extract.rs').read_text() + r'''
fn copy_tree(from: &Path, to: &Path) {
    fs::create_dir_all(to).expect("create application source directory");
    for entry in fs::read_dir(from).expect("read application source") {
        let entry=entry.expect("source entry"); let dest=to.join(entry.file_name());
        if entry.file_type().expect("source file type").is_dir() { copy_tree(&entry.path(),&dest); }
        else { fs::copy(entry.path(),dest).expect("copy application source"); }
    }
}
fn main() {
    println!("cargo:rerun-if-changed=dependencies.tar.xz.b64");
    println!("cargo:rerun-if-changed=src");
    let source=std::path::PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").unwrap());
    let out=std::path::PathBuf::from(env::var_os("OUT_DIR").unwrap());
    let application=out.join("application"); fs::create_dir_all(&application).unwrap();
    extract_archive(&decode(&fs::read(source.join("dependencies.tar.xz.b64")).unwrap()), &application);
    copy_tree(&source.join("src"),&application.join("src"));
    let target=std::path::PathBuf::from(env::var_os("CARGO_TARGET_DIR").expect("Compiler target directory is required"));
    let nested=target.join("source-package-application-target");
    assert!(Command::new(env::var_os("CARGO").unwrap()).current_dir(&application)
        .args(["build","--offline","--locked","--release","--target","wasm32-wasip1"])
        .env("CARGO_TARGET_DIR",&nested).env_remove("CARGO_ENCODED_RUSTFLAGS")
        .status().expect("run offline application compiler").success(),"Application compilation failed");
    let built=nested.join("wasm32-wasip1/release/field-commander-operations.wasm");
    let published=target.join("wasm32-wasip1/release/field-commander-operations.wasm");
    fs::create_dir_all(published.parent().unwrap()).unwrap();
    fs::copy(built,published).expect("stage freshly compiled application for compiler validation");
}
''')
(destination/'SOURCE_PACKAGE.md').write_text('''# Offline source delivery

Application Rust source remains in src/. dependencies.tar.xz.b64 contains the
original Cargo manifest, locked versions, vendored Rust source and licenses.
It contains no compiled binary. The dependency-free transport crate's build.rs
extracts those files and compiles the application using Cargo offline and locked.
A separate nested target directory prevents Cargo lock contention. Only the
freshly compiled application WASM is staged for BlinkHost validation and signing.
Decode with base64 -d and extract with tar -xJf to inspect the dependency sources.
''')
print(json.dumps({'directory':str(destination),'compressed_dependencies':len(compressed),'text_source_bytes':sum(p.stat().st_size for p in destination.rglob('*') if p.is_file())}))
